#!/usr/bin/env python3
"""summarize.py — turn yesterday's terminal log into a daily summary with `claude -p`.
Runs the CLI with NO tools so its stdout is the report, then refuses to save
anything that looks like a confirmation instead of a report."""
import re, subprocess, sys
from datetime import date, timedelta
from pathlib import Path

VAULT = Path(sys.argv[1]).expanduser()
DAY = sys.argv[2] if len(sys.argv) > 2 else (date.today() - timedelta(days=1)).isoformat()
y, m, _ = DAY.split("-")
log = VAULT / "terminal-logs/daily-logs" / y / m / f"{DAY}.md"
out = VAULT / "terminal-logs/daily-summaries" / y / m / f"{DAY}.md"
MIN_CHARS = 400
CONFIRMATION = re.compile(r"^\s*(done|saved|wrote|written|i['’]?ve (saved|written))\b", re.I)

def validate(text: str) -> str:
    text = text.strip()
    first = next((l for l in text.splitlines() if l.strip()), "")
    if CONFIRMATION.match(first): raise SystemExit(f"REJECTED: confirmation, not a report: {first[:80]!r}")
    if not re.search(r"^#{1,4} \S", text, re.M): raise SystemExit("REJECTED: no markdown headings")
    if len(text) < MIN_CHARS: raise SystemExit(f"REJECTED: {len(text)} chars < {MIN_CHARS}")
    return text

if not log.exists(): raise SystemExit(f"no log for {DAY}")
if out.exists(): raise SystemExit(f"summary already exists: {out}")
prompt = f"""Summarize this terminal log for {DAY}. Sections: ## Overview (2 sentences), ## Work sessions (time ranges + what was done), ## Notable commands. Reply with the report only; do not use tools or write files.

{log.read_text()}"""
r = subprocess.run(["claude", "-p", "--allowedTools", "", "--setting-sources", ""],
                   input=prompt, capture_output=True, text=True, timeout=180, cwd=str(Path.home()))
if r.returncode != 0: raise SystemExit(f"CLI failed: {r.stderr[:300]}")
report = validate(r.stdout)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(f"# Daily Summary — {DAY}\n\n> Generated by summarize.py via Claude CLI\n\n{report}\n")
print(f"wrote {out.relative_to(VAULT)} ({len(report)} chars)")
